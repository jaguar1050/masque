// safetyLede, callNow, callSoon, carryOn, noneApply, seenToday, seenWeek) is reviewed first.
// No existing Spanish string is changed: applyLocaleDelta refuses any path that already exists.
//
// Rows:
//   added   {path, after, en, value, basis}: `value` is inserted at `path` (a rubric pointer under
//           /locales/es) right after the sibling `after`, in the English key order (es: reviewed,
//           items, redFlags, contextItems, steps, ui; a step: title, heading, lede, intro; ui: sub,
//           forYouIf, clinicianLede; an item's `clin` after its existing keys). `en` is the English
//           source (/locales/en at the same path; for an item's `clin`, the item's patientClin), so a
//           later English edit is detected. `basis` says which existing Spanish a row reuses, or
//           "new": a string, or for an object or list value an object from each leaf's pointer
//           (relative to `path`) to its basis. Context option values are the English ones, in order.
//   chrome  {key, en, basis}: the PATIENT_CHROME.es keys this release adds. The Spanish values live
//           in src/engine/patient.js (the engine cannot import tests/); `en` is PATIENT_CHROME.en[key].
//   The engine-owned Spanish of this release (CAVEATS, engine cards, shell lines) lives in the
//   engine and shell files, not here: it is not module data.


// One source of truth for three readers, as tests/harness/lexicon-delta.js is for the lexicon:
//   tests/tools/extract-rubric.js  applies `added` to the baseline-extracted locales.es
//                                  (applyLocaleDelta, tests/harness/diff.js), proves it exact with
//                                  revertLocaleDelta, checks each row's `en` against the English
//                                  source, and appends `changelog` after the lexicon entry;
//   tests/suites/values.js         exempts exactly these leaves (pointer + value) from the provenance
//                                  sweep and checks the `chrome` rows against PATIENT_CHROME;
//   the parity suites              name the English → Spanish pairs they may excuse.
